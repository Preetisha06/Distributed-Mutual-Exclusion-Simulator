"""Tests for crash recovery (Ricart-Agrawala timeouts, Token Ring regeneration).

Run with:  python test_recovery.py
"""
import time
from concurrent.futures import ThreadPoolExecutor

from bank import BankAccount, START_BALANCE
from recovery import RecoveringNode, run_ra_scenario, run_ring_scenario

NAMES = ["ATM 1", "ATM 2", "ATM 3"]

# ---- run all 12 scenarios side by side (each watches for ~6.5 s) ----
print("Running 12 crash scenarios (about 7 seconds)...")
with ThreadPoolExecutor(max_workers=12) as pool:
    jobs = {(kind, crashed, recover): pool.submit(run, crashed, recover)
            for kind, run in (("ra", run_ra_scenario), ("ring", run_ring_scenario))
            for crashed in range(3) for recover in (False, True)}
    results = {key: future.result() for key, future in jobs.items()}

for crashed in range(3):
    survivors = [NAMES[i] for i in range(3) if i != crashed]
    dead = NAMES[crashed]

    # ---------- Ricart-Agrawala ----------
    off = results[("ra", crashed, False)]
    on = results[("ra", crashed, True)]
    # no recovery: stuck forever, nobody withdraws
    assert off["completed"] == 0 and off["stuck"] == survivors, off
    assert off["balance"] == START_BALANCE
    # with recovery: both survivors detect the failure, then complete both rounds
    assert on["completed"] == on["wanted"] == 4, on["completed"]
    assert on["balance"] == START_BALANCE - 400 == on["expected_balance"]
    assert on["max_active"] == 1, "mutual exclusion broken!"
    detections = [e for e in on["events"] if e["kind"] == "detected"]
    assert sorted(e["by"] for e in detections) == survivors, detections
    assert all(e["failed"] == dead for e in detections)
    assert all(0.9 <= e["at"] <= 3.0 for e in detections), detections   # about the timeout
    assert not [e for e in on["events"] if e["kind"] == "regenerated"]

    # ---------- Token Ring ----------
    off = results[("ring", crashed, False)]
    on = results[("ring", crashed, True)]
    # no recovery: ATMs before the crashed one get a turn, then the token is lost
    assert off["token_lost"], "token should be lost"
    assert off["completed"] == crashed, (crashed, off["completed"])
    assert off["balance"] == START_BALANCE - 100 * off["completed"]
    # with recovery: exactly one new token, made by the lowest-id alive ATM
    assert on["tokens_created"] == 1, on["tokens_created"]
    regenerated = [e for e in on["events"] if e["kind"] == "regenerated"]
    assert len(regenerated) == 1 and regenerated[0]["by"] == survivors[0], regenerated
    assert sorted(e["by"] for e in on["events"] if e["kind"] == "detected") == survivors
    assert on["completed"] == on["wanted"] == 4, on["completed"]
    assert on["balance"] == START_BALANCE - 400 == on["expected_balance"]
    assert on["max_active"] == 1, "mutual exclusion broken!"
    # the crashed ATM never withdrew
    assert dead not in on["edit_order"]

    print(f"{dead} crashed: RA stuck -> recovers; ring token lost -> regenerated by "
          f"{survivors[0]}; balances correct")


# ---- the limitation: a SLOW (but alive) ATM is wrongly treated as crashed ----
print("Slow ATM limitation")


class SlowNode(RecoveringNode):
    """Alive, but takes 1.6 s to react to any message (longer than the 1.0 s timeout)."""

    def handle(self, message):
        time.sleep(1.6)
        super().handle(message)


account = BankAccount()
events = []
t0 = time.time()
nodes = [RecoveringNode(0, "ATM 1", account, events, t0),
         RecoveringNode(1, "ATM 2", account, events, t0),
         SlowNode(2, "ATM 3", account, events, t0)]
for node in nodes:
    node.daemon = True
    node.log = lambda text: None
    node.peers = [other for other in nodes if other is not node]
nodes[0].wants_edit = True                  # only ATM 1 withdraws
for node in nodes:
    node.start()
end = time.time() + 6
while not nodes[0].done and time.time() < end:
    time.sleep(0.05)
for node in nodes:
    node.stop()

assert nodes[0].done, "ATM 1 should have carried on without ATM 3"
wrongly = [e for e in events if e["by"] == "ATM 1" and e["failed"] == "ATM 3"]
assert wrongly, "the slow ATM 3 should have been wrongly treated as crashed"
print(f"   ATM 3 was alive but ATM 1 gave up on it at +{wrongly[0]['at']} s (false positive)")

print("\nAll recovery tests passed.")
